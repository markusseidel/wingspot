do $$
declare
  def text := pg_get_functiondef('private.register_country(text)'::regprocedure);
  marker text := E'  if v_prefix = ''B'' then';
  territories text := E'  if v_prefix in (''VP'', ''VQ'', ''VR'') then\n'
    || E'    return case substr(v_mark, 1, 1)\n'
    || E'      when ''A'' then ''AI'' when ''B'' then ''BM'' when ''C'' then ''KY'' when ''F'' then ''FK''\n'
    || E'      when ''G'' then ''GI'' when ''H'' then ''SH'' when ''L'' then ''VG'' when ''M'' then ''MS''\n'
    || E'      when ''T'' then ''TC'' else ''GB'' end;\n'
    || E'  end if;\n';
begin
  if position(marker in def) = 0 then raise exception 'register_country changed: marker not found'; end if;
  execute replace(def, marker, territories || marker);
end $$;


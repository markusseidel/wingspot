-- Server data model (docs/CONCEPT.md §11.3). Access rules are in the next migration.
--
-- Differences from the concept:
-- - Tables are ordered so that references resolve.
-- - User-owned rows cascade from auth.users, so account deletion removes them.
-- - app_config and refdata_snapshots back /v1/config and /v1/refdata/manifest.

create extension if not exists postgis schema extensions;

-- Reference data
create table public.airports (
  id            integer generated by default as identity primary key,
  icao          text unique,
  iata          text,
  name          text not null,
  city          text,
  country_code  char(2) not null,
  continent     char(2) not null,
  elevation_ft  integer,
  location      extensions.geography(point, 4326) not null,
  geofence      extensions.geography(polygon, 4326),
  is_island     boolean not null default false,
  min_runway_m  integer
);
create index airports_iata_idx on public.airports (iata);
create index airports_location_idx on public.airports using gist (location);

create table public.aircraft_types (
  icao_code          text primary key,
  manufacturer       text not null,
  model              text not null,
  family             text,
  engine_type        text,
  engine_count       integer,
  wtc                char(1) check (wtc in ('L', 'M', 'H', 'J')),
  in_service_count   integer,
  entry_into_service date
);

create table public.operators (
  id            integer generated by default as identity primary key,
  icao          text unique,
  iata          text,
  name          text not null,
  country_code  char(2),
  alliance      text,
  category      text
);

create table public.aircraft (
  id            integer generated by default as identity primary key,
  registration  text unique not null,
  icao24        char(6),
  type_icao     text references public.aircraft_types,
  operator_id   integer references public.operators,
  msn           text,
  first_flight  date,
  livery        text,
  livery_name   text,
  is_sensitive  boolean not null default false,
  data_status   text not null default 'verified'
                check (data_status in ('verified', 'pending', 'user_submitted'))
);

-- Remote configuration: exactly one row
create table public.app_config (
  id                  boolean primary key default true check (id),
  min_version_ios     text not null,
  min_version_android text not null,
  feature_flags       jsonb not null default '{}' check (jsonb_typeof(feature_flags) = 'object')
);
insert into public.app_config (min_version_ios, min_version_android) values ('0.1.0', '0.1.0');

create table public.refdata_snapshots (
  id             bigint generated always as identity primary key,
  schema_version integer not null,
  data_version   text not null unique,
  url            text not null,
  sha256         text not null check (sha256 ~ '^[0-9a-f]{64}$'),
  size_bytes     bigint not null check (size_bytes >= 0),
  published_at   timestamptz not null default now()
);

-- User data
create table public.profiles (
  id            uuid primary key references auth.users on delete cascade,
  username      text unique not null check (username ~ '^[a-z0-9_]{3,30}$'),
  display_name  text check (char_length(display_name) <= 100),
  avatar_url    text,
  home_airport  integer references public.airports,
  xp            integer not null default 0,
  is_private    boolean not null default false,
  post_delay_minutes integer not null default 0 check (post_delay_minutes between 0 and 1440),
  created_at    timestamptz not null default now()
);

create type public.checkin_kind as enum ('spotted', 'flown', 'airport');
create type public.verification as enum ('none', 'location', 'adsb', 'boarding_pass');

create table public.sessions (
  id          uuid primary key,
  user_id     uuid not null references public.profiles on delete cascade,
  airport_id  integer references public.airports,
  started_at  timestamptz,
  ended_at    timestamptz
);

create table public.spotting_locations (
  id          integer generated by default as identity primary key,
  airport_id  integer not null references public.airports,
  name        text not null,
  location    extensions.geography(point, 4326),
  description text,
  best_time   text,
  legal_notes text,
  created_by  uuid references public.profiles on delete set null,
  status      text not null default 'pending' check (status in ('pending', 'approved', 'rejected'))
);

create table public.checkins (
  id            uuid primary key,
  user_id       uuid not null references public.profiles on delete cascade,
  kind          public.checkin_kind not null,
  occurred_at   timestamptz not null,
  created_at    timestamptz not null default now(),
  aircraft_id   integer references public.aircraft,
  type_icao     text references public.aircraft_types,
  operator_id   integer references public.operators,
  airport_id    integer references public.airports,
  spot_location_id integer references public.spotting_locations on delete set null,
  location      extensions.geography(point, 4326),
  phase         text,
  tags          text[] not null default '{}',
  note          text,
  rating        smallint check (rating between 1 and 5),
  session_id    uuid references public.sessions on delete set null,
  verification  public.verification not null default 'none',
  visibility    text not null default 'public' check (visibility in ('public', 'friends', 'private')),
  flight_number text,
  origin_id     integer references public.airports,
  destination_id integer references public.airports,
  distance_km   integer,
  cabin_class   text,
  seat          text
);
create index checkins_user_idx on public.checkins (user_id, occurred_at desc);
create index checkins_airport_idx on public.checkins (airport_id, occurred_at desc);
create index checkins_aircraft_idx on public.checkins (aircraft_id);

create table public.checkin_photos (
  id           uuid primary key,
  checkin_id   uuid not null references public.checkins on delete cascade,
  storage_path text not null,
  width        integer,
  height       integer,
  position     smallint
);
create index checkin_photos_checkin_idx on public.checkin_photos (checkin_id);

create table public.badges (
  id                text primary key,
  name              text not null,
  description       text,
  category          text,
  kind              text,
  rule              jsonb not null,
  levels            integer[],
  requires_verified boolean not null default false,
  hidden            boolean not null default false,
  valid_from        timestamptz,
  valid_until       timestamptz,
  art_url           text
);

create table public.user_badges (
  user_id     uuid not null references public.profiles on delete cascade,
  badge_id    text not null references public.badges,
  level       integer,
  progress    integer,
  unlocked_at timestamptz,
  checkin_id  uuid references public.checkins on delete set null,
  primary key (user_id, badge_id)
);

-- Devices and push: one row per installed app instance
create type public.platform as enum ('ios', 'android');

create table public.devices (
  id            uuid primary key,
  user_id       uuid not null references public.profiles on delete cascade,
  platform      public.platform not null,
  push_token    text,
  push_env      text check (push_env in ('sandbox', 'production')),
  app_version   text not null,
  os_version    text,
  locale        text,
  last_seen_at  timestamptz not null default now(),
  unique (platform, push_token)
);
create index devices_user_idx on public.devices (user_id);

create table public.notification_prefs (
  user_id          uuid primary key references public.profiles on delete cascade,
  salutes          boolean not null default true,
  comments         boolean not null default true,
  new_followers    boolean not null default true,
  friend_badges    boolean not null default false,
  wishlist_alerts  boolean not null default false,
  airport_geofence boolean not null default false
);

-- Subscriptions: entitlements apply to the user, whichever store sold them
create type public.store as enum ('app_store', 'play_store', 'promo');

create table public.entitlements (
  user_id     uuid not null references public.profiles on delete cascade,
  entitlement text not null,
  store       public.store not null,
  product_id  text not null,
  original_transaction_id text not null,
  status      text not null,
  expires_at  timestamptz,
  auto_renew  boolean,
  updated_at  timestamptz not null default now(),
  primary key (user_id, entitlement, store)
);

create table public.store_events (
  id           uuid primary key,
  store        public.store not null,
  payload      jsonb not null,
  received_at  timestamptz not null default now(),
  processed_at timestamptz
);

-- Social
create table public.follows (
  follower   uuid not null references public.profiles on delete cascade,
  followee   uuid not null references public.profiles on delete cascade,
  created_at timestamptz not null default now(),
  primary key (follower, followee),
  check (follower <> followee)
);
create index follows_followee_idx on public.follows (followee);

create table public.salutes (
  user_id    uuid not null references public.profiles on delete cascade,
  checkin_id uuid not null references public.checkins on delete cascade,
  primary key (user_id, checkin_id)
);
create index salutes_checkin_idx on public.salutes (checkin_id);

create table public.comments (
  id         uuid primary key default gen_random_uuid(),
  checkin_id uuid not null references public.checkins on delete cascade,
  user_id    uuid not null references public.profiles on delete cascade,
  body       text not null check (char_length(body) between 1 and 2000),
  created_at timestamptz not null default now()
);
create index comments_checkin_idx on public.comments (checkin_id, created_at);

create table public.reports (
  id          uuid primary key default gen_random_uuid(),
  reporter    uuid references public.profiles on delete set null,
  target_type text not null,
  target_id   text not null,
  reason      text,
  status      text not null default 'open'
);

create table public.blocks (
  blocker uuid not null references public.profiles on delete cascade,
  blocked uuid not null references public.profiles on delete cascade,
  primary key (blocker, blocked),
  check (blocker <> blocked)
);
create index blocks_blocked_idx on public.blocks (blocked);
